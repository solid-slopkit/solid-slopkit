import { inferParams, renderParamType } from '../message/params';
import { parseMessage } from '../message/parse';
import type { MessageTree } from './validate';

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const property = (key: string) => (IDENTIFIER.test(key) ? key : JSON.stringify(key));

/**
 * The declaration file for one translation file: the default locale's shape. A message without
 * arguments is a `string`; one with arguments is a function of a typed parameters object.
 * Pairs with `allowArbitraryExtensions` (see `typesFileFor`).
 */
export function generateTypes(messages: MessageTree): string {
  return `// Generated by @solid-slopkit/i18n. Do not edit.\ndeclare const messages: ${renderTree(messages, '')};\nexport default messages;\n`;
}

function renderTree(tree: MessageTree, indent: string): string {
  const inner = `${indent}  `;
  const lines = Object.entries(tree).map(([key, child]) => {
    return `${inner}readonly ${property(key)}: ${typeof child === 'string' ? renderMessage(child) : renderTree(child, inner)};`;
  });
  return lines.length === 0 ? '{}' : `{\n${lines.join('\n')}\n${indent}}`;
}

function renderMessage(text: string): string {
  const params = inferParams(parseMessage(text));
  if (params.size === 0) return 'string';
  const fields = [...params].map(([name, kind]) => `readonly ${property(name)}: ${renderParamType(kind)}`);
  return `(params: { ${fields.join('; ')} }) => string`;
}
