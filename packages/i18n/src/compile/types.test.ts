import { expect, test } from 'vitest';
import { generateTypes } from './types';

test('renders the default locale as readonly string properties, nested like the file', () => {
  expect(generateTypes({ title: 'Users', form: { submit: 'Save', errors: { required: 'Required' } } })).toBe(
    `// Generated by @solid-slopkit/i18n. Do not edit.
declare const messages: {
  readonly title: string;
  readonly form: {
    readonly submit: string;
    readonly errors: {
      readonly required: string;
    };
  };
};
export default messages;
`,
  );
});

test('quotes keys that are not identifiers, and renders an empty group as {}', () => {
  expect(generateTypes({ 'a-b': 'x', '1st': 'y', empty: {} })).toContain('readonly "a-b": string;');
  expect(generateTypes({ '1st': 'y', empty: {} })).toContain('readonly "1st": string;');
  expect(generateTypes({ empty: {} })).toContain('readonly empty: {};');
});

test('a message with arguments is a function of a typed parameters object', () => {
  const output = generateTypes({
    plain: 'Hello',
    greeting: 'Hi {name}',
    items: '{n, plural, one {# item} other {# items}}',
    when: 'On {d, date, long}, {role, select, admin {an admin} other {someone}} signed {n, number}',
    group: { nested: 'Bye {name}' },
  });
  expect(output).toContain('readonly plain: string;');
  expect(output).toContain('readonly greeting: (params: { readonly name: string | number }) => string;');
  expect(output).toContain('readonly items: (params: { readonly n: number }) => string;');
  expect(output).toContain(
    'readonly when: (params: { readonly d: Date | number; readonly role: "admin" | (string & {}); readonly n: number }) => string;',
  );
  expect(output).toContain('readonly nested: (params: { readonly name: string | number }) => string;');
});
