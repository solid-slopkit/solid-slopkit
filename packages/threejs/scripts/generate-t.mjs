// Generates src/t/components.gen.ts: one Scene component for each scene-graph class three.js exports (objects,
// cameras, lights, helpers, geometries, materials, textures, fog), exposed as the `T` namespace (ADR 0025).
//
// Only classes that both the installed three and the lowest supported one (the `three-floor` dev dependency, which
// tracks the peer range's minimum) export are included: importing a newer class would break consumers on an older
// three. Run `pnpm generate` after changing either version; `--check` fails when the file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const BASES = ['Object3D', 'BufferGeometry', 'Material', 'Texture', 'Fog', 'FogExp2'];
// Declared abstract in @types/three: only its subclasses are constructed.
const ABSTRACT = new Set(['Light']);
const output = fileURLToPath(new URL('../src/t/components.gen.ts', import.meta.url));

// three's `exports` hide its package.json, so both are read from this package's node_modules.
async function load(name) {
  const root = new URL(`../node_modules/${name}/`, import.meta.url);
  const { version } = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
  const THREE = await import(new URL('build/three.module.js', root).href);
  return { version, THREE };
}

// Classes exported under their own name (not deprecated aliases) that are, or extend, one of the bases.
function sceneClasses(THREE) {
  const names = [];
  for (const [name, value] of Object.entries(THREE)) {
    if (typeof value !== 'function' || !value.prototype || value.name !== name || ABSTRACT.has(name)) continue;
    if (BASES.some((base) => value === THREE[base] || value.prototype instanceof THREE[base])) names.push(name);
  }
  return names;
}

const current = await load('three');
const floor = await load('three-floor');
const supported = new Set(sceneClasses(floor.THREE));
const names = sceneClasses(current.THREE)
  .filter((name) => supported.has(name))
  .sort();

const minor = (version) => `r${version.split('.')[1]}`;
const source = `// Generated by scripts/generate-t.mjs from three ${minor(current.version)}, limited to the classes three ${minor(floor.version)} also
// exports. Don't edit: run \`pnpm generate\`.
import {
${names.map((name) => `  ${name} as Three${name},`).join('\n')}
} from 'three';
import { sceneComponent } from '../scene-component';

${names.map((name) => `export const ${name} = /* @__PURE__ */ sceneComponent(Three${name});`).join('\n')}
`;

if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(output, 'utf8');
  } catch {}
  if (committed !== source) {
    console.error('src/t/components.gen.ts is out of date: run `pnpm generate`.');
    process.exit(1);
  }
} else {
  writeFileSync(output, source);
  console.log(`Wrote ${names.length} Scene components to src/t/components.gen.ts.`);
}
